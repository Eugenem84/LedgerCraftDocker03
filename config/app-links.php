<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Ссылки из писем в приложение (deep links)
    |--------------------------------------------------------------------------
    |
    | Клиент Ledger Craft — Android-приложение (Capacitor), веб-версии пока нет,
    | поэтому ссылки в письмах («подтвердите почту», «сбросьте пароль») не могут
    | вести на страницу SPA. Вместо этого каждая ссылка ведёт на https-адрес
