    |
    |   • reset_path    — bridge-страница сброса пароля. Android App Links может
    |                     открыть приложение сразу, минуя браузер; если домен ещё
    |                     не верифицирован — страница пробует схему приложения.
    |   • verified_path — куда подтверждающее письмо уводит после проверки подписи;
    |                     приложение открывается прямо на этом https-адресе.
    |
    | Мейл-клиенты часто вырезают нестандартные схемы (`ledgercraft://`), поэтому
    | письма всегда используют https, а схема — только как фолбэк на bridge-странице.
    |
    | Верификация домена для App Links — статический файл
    | `public/.well-known/assetlinks.json` (отпечаток ключа подписи APK).
    */

    // Схема приложения. Меняется только вместе с intent-filter в
    // `src-capacitor/android/app/src/main/AndroidManifest.xml`.
    'scheme' => env('APP_DEEP_LINK_SCHEME', 'ledgercraft'),

    // https-путь bridge-страницы сброса пароля (ссылка в письме «сброс пароля»).
    'reset_path' => env('APP_LINKS_RESET_PATH', '/app/reset'),

    // https-путь, куда уводит ссылка подтверждения почты после проверки подписи.
    'verified_path' => env('APP_LINKS_VERIFIED_PATH', '/app/verified'),

    /*
    | Имена веток приложения для схемы `ledgercraft://<имя>?...`. Значения должны
    | совпадать с `src/router/routes.js` клиента: bridge-страница собирает из них
    | deep link, а boot-файл `src/boot/deepLinks.js` разбирает обратно.
    */
    'deep_links' => [
        'reset_password' => 'reset-password',
        'verify_email' => 'verify-email',
    ],

    /*
    | Срок жизни ссылки подтверждения почты (минуты). Тот же ключ читает
    | уведомление; Laravel использует `auth.verification.expire`, если он задан.
    */
    'verification_expire' => (int) env('APP_LINKS_VERIFICATION_EXPIRE', 60),

];
